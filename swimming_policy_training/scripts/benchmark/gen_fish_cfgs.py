#!/usr/bin/env python
"""Generate per-fish Isaac Lab cfg classes + gym registrations for the benchmark fish.

For every fish tag in fish_list.json (traj list) it emits, into
source/FISH/FISH/tasks/direct/fish/salmon_benchmark_fish_cfgs.py:
  <Cls>CalibCfg                 (SalmonSwimEnv, for scripts/benchmark/calibrate_fish.py)
  <Cls>PCATrajFollowCfg         BLM+RL (PCA action space), kp=120, jlim=25 (fish_pure_rl settings)
  <Cls>JointTrajFollowCfg       Joint RL
and appends gym.register blocks (idempotent) to __init__.py:
  Bench-<tag>-Calib-v0, Bench-<tag>-TrajFollow-PCA-v0, Bench-<tag>-TrajFollow-Joint-v0,
  Bench-<tag>-Reach10-PCA-v0 (BL-scaled target geometry)
Per-fish inputs (all produced by the Video2SwimFish pipeline):
  data/fish_assets/<tag>/K_final.usd, panel_hydro.npz, calibration.npz (from calibrate_fish.py)
  data/species_manifold/<species>_fix/top/fish<NNN>_pca_basis.npz, fish<NNN>_reference.npz, fish<NNN>_curvature.npz
  data/species_manifold/<species>/fish_sizes.json (body length)
"""
import argparse, json, re
from pathlib import Path
REPO = Path(__file__).resolve().parents[2]; TASKDIR = REPO / "source/FISH/FISH/tasks/direct/fish"
# Actuator preset. PAPER SETTINGS (Sec. 4.1 / App. C): PD stiffness kp = 120, joint limit = +-45 deg, kd = SWIM_DAMPING = 6.
# (The unfinished 2026-09-29 sweep in the research checkout used kp=240 / jlim=80; pass --kp 240 --jlim 80 to reproduce it.)
# If a fish blows up, raise ITS damping (restoring the kd/kp ratio) rather than lowering kp.
KP = 120.0; JLIM = 45.0; PCA_MODES = None

def cls_name(tag):  # catfish_fish002 -> CatfishFish002
    return "".join(p.capitalize() for p in tag.split("_"))

def main():
    global KP, JLIM, PCA_MODES
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    ap.add_argument('--kp', type=float, default=KP, help='PD stiffness of every joint DoF (paper: 120)')
    ap.add_argument('--jlim', type=float, default=JLIM, help='joint limit in degrees (paper: 45)')
    ap.add_argument('--pca_modes', type=int, default=None, help='number of BLM PCA modes the policy controls (code default 20; paper text: 4)')
    a = ap.parse_args(); KP, JLIM, PCA_MODES = a.kp, a.jlim, a.pca_modes
    fl = json.load(open(REPO / "scripts/benchmark/fish_list.json"))
    tags = sorted(set(fl["traj"]) | set(fl["freeswim"]))
    out = ['# AUTO-GENERATED by scripts/benchmark/gen_fish_cfgs.py -- do not edit by hand.',
           '"""Per-fish benchmark cfgs (kp=%.0f, joint_limit_deg=%.0f = fish_pure_rl settings)."""' % (KP, JLIM),
           'from __future__ import annotations', 'import copy, json', 'from pathlib import Path', 'import numpy as np',
           'from isaaclab.assets import ArticulationCfg', 'from isaaclab.utils import configclass',
           'from .salmon_swim_amp_misty_panels_cfg import SalmonSwimAMPMistyPanelsCfg, _ART_PANELS',
           'from .salmon_swim_traj_follow_cfg import SalmonSwimPCATrajFollowCfg, SalmonSwimJointTrajFollowCfg, SalmonSwimCPGTrajFollowCfg, SalmonSwimJointAMPTrajFollowCfg',
           'from .salmon_rov_catch_bench_env import BenchROVCatchCfg',
           'from .salmon_swim_pca_videostate_cfg import SalmonSwimPCAVideoStateCfg',
           'from .salmon_swim_reach10_cfg import SalmonSwimPCAReach10Cfg',
           '# Reach10 protocol distances were tuned for the 0.5 m Misty asset; every length below is',
           '# re-expressed in BODY LENGTHS of that reference and re-dimensioned per fish, so a 6.7 cm',
           '# white bass and a 31 cm catfish face the SAME task in BL units (option A, 2026-09-24).',
           'MISTY_BL = 0.5',
           '_REPO = Path(__file__).resolve().parents[6]   # <repo>/source/FISH/FISH/tasks/direct/fish/<this file>', f'KP = {KP}', f'JLIM = {JLIM}', f'JLIM_CALIB = {JLIM}', '',
           'def _load_calib(p):',
           '    if p.exists():',
           '        c = np.load(p, allow_pickle=True)',
           '        return str(c["control_dof_suffix"]), float(c["body_forward_sign"]) if "body_forward_sign" in c.files else 1.0',
           '    return ":1", 1.0   # head is at +X in every a2c asset (2026-09-24 fix; was -1.0, copied from Misty)', '',
           'def _body_length(species, num):',
           '    d = json.load(open(_REPO / f"data/species_manifold/{species}/fish_sizes.json"))',
           '    return float(d["per_fish"][num]["length_m"])', '']
    regs = []
    for tag in tags:
        m = re.match(r"^(.*)_fish(\d+)(?:_(.+))?$", tag); sp, num = m.group(1), m.group(2); C = cls_name(tag)
        # a variant tag (e.g. white_bass_fish008_nohead) is the SAME real fish: it reuses that
        # fish's video-derived PCA basis / reference / curvature and its measured body length.
        out += [f'# ---------------------------------------------------------------- {tag}',
                f'_D_{C} = _REPO / "data/fish_assets/{tag}"',
                f'_M_{C} = _REPO / "data/species_manifold/{sp}_fix/top"',
                f'_ART_{C}: ArticulationCfg = copy.deepcopy(_ART_PANELS)',
                f'_ART_{C}.spawn.usd_path = str(_D_{C} / "K_final.usd")',
                f'_ART_{C}.actuators["all_joints"].stiffness = KP',
                f'_SUF_{C}, _FWD_{C} = _load_calib(_D_{C} / "calibration.npz")',
                f'_BL_{C} = _body_length("{sp}", "{num}")', '',
                '@configclass', f'class {C}CalibCfg(SalmonSwimAMPMistyPanelsCfg):',
                f'    robot_cfg: ArticulationCfg = _ART_{C}', '    deformable_prim_token = "Mesh_0"', '    keep_bone_colliders = False   # BUG FIX 2026-09-22: inherited True from the autoskel tank cfg -> bone colliders fought the attached FEM skin',
                f'    panel_hydro_path = str(_D_{C} / "panel_hydro.npz")', f'    body_length = _BL_{C}',
                '    control_dof_suffix = None', '    joint_limit_deg = JLIM_CALIB',
                '    draw_target_marker = False', '    marker_success_sphere = False',
                '    curriculum = False', '    dist_curriculum = False', '    multi_target = False', '',
                '@configclass', f'class {C}PCATrajFollowCfg(SalmonSwimPCATrajFollowCfg):',
                f'    robot_cfg: ArticulationCfg = _ART_{C}', '    deformable_prim_token = "Mesh_0"', '    keep_bone_colliders = False   # BUG FIX 2026-09-22: inherited True from the autoskel tank cfg -> bone colliders fought the attached FEM skin',
                f'    panel_hydro_path = str(_D_{C} / "panel_hydro.npz")',
                f'    pca_calib_path = str(_D_{C} / "calibration.npz")', '    pca_phi_mode = "analytic"',
                f'    pca_basis_path = str(_M_{C} / "fish{num}_pca_basis.npz")',
                f'    body_length = _BL_{C}', f'    control_dof_suffix = _SUF_{C}', f'    body_forward_sign = _FWD_{C}',
                '    joint_limit_deg = JLIM',] + ([f'    pca_num_modes = {PCA_MODES}',] if PCA_MODES else []) + [
                f'    zef_traj_path = str(_M_{C} / "fish{num}_reference.npz")',
                f'    ref_curvature_path = str(_M_{C} / "fish{num}_curvature.npz")', f'    fish_tag = "{tag}"', '',
                '@configclass', f'class {C}PCAReach10Cfg(SalmonSwimPCAReach10Cfg):',
                f'    robot_cfg: ArticulationCfg = _ART_{C}', '    deformable_prim_token = "Mesh_0"', '    keep_bone_colliders = False',
                f'    panel_hydro_path = str(_D_{C} / "panel_hydro.npz")',
                f'    pca_calib_path = str(_D_{C} / "calibration.npz")', '    pca_phi_mode = "analytic"',
                f'    pca_basis_path = str(_M_{C} / "fish{num}_pca_basis.npz")',
                f'    body_length = _BL_{C}', f'    control_dof_suffix = _SUF_{C}', f'    body_forward_sign = _FWD_{C}',
                '    joint_limit_deg = JLIM',] + ([f'    pca_num_modes = {PCA_MODES}',] if PCA_MODES else []) + [
                f'    ref_curvature_path = str(_M_{C} / "fish{num}_curvature.npz")', f'    fish_tag = "{tag}"',
                f'    # --- BL-scaled Reach10 geometry (Misty values / {{MISTY_BL}} m * this fish\'s BL) ---',
                f'    success_radius = 0.4 * _BL_{C}          # Misty 0.20 m = 0.40 BL',
                f'    target_dist_mean = 2.0 * _BL_{C}        # Misty 1.00 m = 2.00 BL',
                f'    target_dist_std = 0.5 * _BL_{C}         # Misty 0.25 m = 0.50 BL',
                f'    target_dist_clamp_max = 3.6 * _BL_{C}   # Misty 1.80 m = 3.60 BL',
                f'    target_dist_clamp_pad = 0.4 * _BL_{C}   # was a hard-coded 0.2 m; see salmon_swim_env._resample_targets',
                f'    attempt_abort_dist = 6.0 * _BL_{C}      # Misty 3.00 m = 6.00 BL',
                f'    root_position_limit = 60.0 * _BL_{C}    # Misty 30.0 m = 60.0 BL',
                '    # attempt_timeout_s / episode_length_s are NOT scaled: distances scale with BL and',
                '    # swim speed is measured in BL/s, so time-to-target is already scale-invariant.',
                '',
                '@configclass', f'class {C}JointTrajFollowCfg(SalmonSwimJointTrajFollowCfg):',
                f'    robot_cfg: ArticulationCfg = _ART_{C}', '    deformable_prim_token = "Mesh_0"', '    keep_bone_colliders = False   # BUG FIX 2026-09-22: inherited True from the autoskel tank cfg -> bone colliders fought the attached FEM skin',
                f'    panel_hydro_path = str(_D_{C} / "panel_hydro.npz")',
                f'    pca_calib_path = str(_D_{C} / "calibration.npz")', '    pca_phi_mode = "analytic"',
                f'    pca_basis_path = str(_M_{C} / "fish{num}_pca_basis.npz")',
                f'    body_length = _BL_{C}', f'    control_dof_suffix = _SUF_{C}', f'    body_forward_sign = _FWD_{C}',
                '    joint_limit_deg = JLIM',] + ([f'    pca_num_modes = {PCA_MODES}',] if PCA_MODES else []) + [
                f'    zef_traj_path = str(_M_{C} / "fish{num}_reference.npz")',
                f'    ref_curvature_path = str(_M_{C} / "fish{num}_curvature.npz")', f'    fish_tag = "{tag}"', '',
                '@configclass', f'class {C}JointAMPTrajFollowCfg(SalmonSwimJointAMPTrajFollowCfg):',
                f'    robot_cfg: ArticulationCfg = _ART_{C}', '    deformable_prim_token = "Mesh_0"', '    keep_bone_colliders = False   # BUG FIX 2026-09-22: inherited True from the autoskel tank cfg -> bone colliders fought the attached FEM skin',
                f'    panel_hydro_path = str(_D_{C} / "panel_hydro.npz")',
                f'    pca_calib_path = str(_D_{C} / "calibration.npz")', '    pca_phi_mode = "analytic"',
                f'    pca_basis_path = str(_M_{C} / "fish{num}_pca_basis.npz")',
                f'    amp_reference_path = str(_D_{C} / "amp_reference.npz")',
                f'    disc_ckpt_path = str(_D_{C} / "amp_disc_state.pth")',
                f'    body_length = _BL_{C}', f'    control_dof_suffix = _SUF_{C}', f'    body_forward_sign = _FWD_{C}',
                '    joint_limit_deg = JLIM',] + ([f'    pca_num_modes = {PCA_MODES}',] if PCA_MODES else []) + [
                f'    zef_traj_path = str(_M_{C} / "fish{num}_reference.npz")',
                f'    ref_curvature_path = str(_M_{C} / "fish{num}_curvature.npz")', f'    fish_tag = "{tag}"', '',
                '@configclass', f'class {C}CPGTrajFollowCfg(SalmonSwimCPGTrajFollowCfg):',
                f'    robot_cfg: ArticulationCfg = _ART_{C}', '    deformable_prim_token = "Mesh_0"', '    keep_bone_colliders = False   # BUG FIX 2026-09-22: inherited True from the autoskel tank cfg -> bone colliders fought the attached FEM skin',
                f'    panel_hydro_path = str(_D_{C} / "panel_hydro.npz")',
                f'    pca_calib_path = str(_D_{C} / "calibration.npz")', '    pca_phi_mode = "analytic"',
                f'    pca_basis_path = str(_M_{C} / "fish{num}_pca_basis.npz")',
                f'    cpg_params_path = str(_D_{C} / "cpg_params.npz")',
                f'    body_length = _BL_{C}', f'    control_dof_suffix = _SUF_{C}', f'    body_forward_sign = _FWD_{C}',
                '    joint_limit_deg = JLIM',] + ([f'    pca_num_modes = {PCA_MODES}',] if PCA_MODES else []) + [
                f'    zef_traj_path = str(_M_{C} / "fish{num}_reference.npz")',
                f'    ref_curvature_path = str(_M_{C} / "fish{num}_curvature.npz")', f'    fish_tag = "{tag}"', '',
                '@configclass', f'class {C}FreeSwimVideoStateCfg(SalmonSwimPCAVideoStateCfg):',
                f'    robot_cfg: ArticulationCfg = _ART_{C}', '    deformable_prim_token = "Mesh_0"',
                f'    spawn_glide_speed = 0.15 * _BL_{C}   # m/s: ~video mean forward speed (0.15 BL/s); the fixed 0.05 m/s was 0.75 BL/s for a 6.7 cm fish', '    keep_bone_colliders = False   # BUG FIX 2026-09-22: inherited True from the autoskel tank cfg -> bone colliders fought the attached FEM skin',
                f'    panel_hydro_path = str(_D_{C} / "panel_hydro.npz")',
                f'    pca_calib_path = str(_D_{C} / "calibration.npz")', '    pca_phi_mode = "analytic"',
                f'    pca_basis_path = str(_M_{C} / "fish{num}_pca_basis.npz")',
                f'    body_length = _BL_{C}', f'    control_dof_suffix = _SUF_{C}', f'    body_forward_sign = _FWD_{C}',
                '    joint_limit_deg = JLIM',] + ([f'    pca_num_modes = {PCA_MODES}',] if PCA_MODES else []) + [
                f'    zef_traj_path = str(_M_{C} / "fish{num}_reference.npz")',
                f'    ref_curvature_path = str(_M_{C} / "fish{num}_curvature.npz")', f'    fish_tag = "{tag}"', ''
                '@configclass', f'class {C}ROVCatchCfg(BenchROVCatchCfg):',
                f'    robot_cfg: ArticulationCfg = _ART_{C}', '    deformable_prim_token = "Mesh_0"', '    keep_bone_colliders = False   # BUG FIX 2026-09-22: inherited True from the autoskel tank cfg -> bone colliders fought the attached FEM skin',
                f'    panel_hydro_path = str(_D_{C} / "panel_hydro.npz")',
                f'    pca_calib_path = str(_D_{C} / "calibration.npz")', '    pca_phi_mode = "analytic"',
                f'    pca_basis_path = str(_M_{C} / "fish{num}_pca_basis.npz")',
                f'    body_length = _BL_{C}', f'    control_dof_suffix = _SUF_{C}', f'    body_forward_sign = _FWD_{C}',
                '    joint_limit_deg = JLIM',] + ([f'    pca_num_modes = {PCA_MODES}',] if PCA_MODES else []) + [
                f'    fish_ckpt = str(_REPO / "checkpoints/benchmark/blm_il/{tag}/bc_policy.pt")', f'    fish_tag = "{tag}"', '']
        for suffix, entry, cfgc, yaml in (("TrajFollow-Joint-AMP", "salmon_swim_traj_follow_env:SalmonSwimJointAMPTrajFollowEnv", f"{C}JointAMPTrajFollowCfg", "rl_games_ppo_traj_follow_joint_cfg.yaml"),
                                          ("TrajFollow-CPG", "salmon_swim_traj_follow_env:SalmonSwimCPGTrajFollowEnv", f"{C}CPGTrajFollowCfg", "rl_games_ppo_traj_follow_pca_cfg.yaml"),
                                          ("FreeSwim-VideoState", "salmon_swim_pca_videostate_env:SalmonSwimPCAVideoStateEnv", f"{C}FreeSwimVideoStateCfg", "rl_games_ppo_pca_videostate_cfg.yaml"),("ROVCatch", "salmon_rov_catch_bench_env:BenchROVCatchEnv", f"{C}ROVCatchCfg", "rl_games_ppo_rov_chase_cfg.yaml"),("Calib", "salmon_swim_env:SalmonSwimEnv", f"{C}CalibCfg", "rl_games_ppo_cfg.yaml"),
                                          ("TrajFollow-PCA", "salmon_swim_traj_follow_env:SalmonSwimPCATrajFollowEnv", f"{C}PCATrajFollowCfg", "rl_games_ppo_traj_follow_pca_cfg.yaml"),
                                          ("TrajFollow-Joint", "salmon_swim_traj_follow_env:SalmonSwimJointTrajFollowEnv", f"{C}JointTrajFollowCfg", "rl_games_ppo_traj_follow_joint_cfg.yaml"),
                                          ("Reach10-PCA", "salmon_swim_reach10_env:SalmonSwimPCAReach10Env", f"{C}PCAReach10Cfg", "rl_games_ppo_reach10_pca_cfg.yaml")):
            regs.append(f'gym.register(id="Bench-{tag}-{suffix}-v0", entry_point=f"{{__name__}}.{entry}", disable_env_checker=True,\n'
                        f'    kwargs={{"env_cfg_entry_point": f"{{__name__}}.salmon_benchmark_fish_cfgs:{cfgc}", "rl_games_cfg_entry_point": f"{{agents.__name__}}:{yaml}"}})')
    (TASKDIR / "salmon_benchmark_fish_cfgs.py").write_text("\n".join(out) + "\n")
    init = (TASKDIR / "__init__.py").read_text()
    marker = "# ---- BENCHMARK FISH (auto-generated by scripts/benchmark/gen_fish_cfgs.py) ----"
    if marker in init:
        init = init.split(marker)[0].rstrip() + "\n"
    init += "\n" + marker + "\n" + "\n".join(regs) + "\n"
    (TASKDIR / "__init__.py").write_text(init)
    print(f"generated cfgs for {len(tags)} fish and {len(regs)} gym ids")

if __name__ == "__main__":
    main()
